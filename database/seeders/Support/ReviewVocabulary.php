    /**
     * نوع قطعه را از روی عنوان محصول حدس می‌زند.
     *
     * عنوان‌های کاتالوگ ایساکو تمیز نیستند («مجموعه قاب زیرورویی فرمان -
     * خاکستری ذغالی»)، پس تطابق ساده‌ی زیررشته‌ای انتخاب شد: هر چیز
     * پیچیده‌تری روی این داده‌ها فقط شکننده‌تر می‌شود.
     */
    public static function domainOf(string $title): string
    {
        foreach (self::DOMAINS as $domain => $keywords) {
            foreach ($keywords as $keyword) {
                if (mb_strpos($title, $keyword) !== false) {
                    return $domain;
                }
            }
        }

        return 'generic';
    }

    /**
     * مخزن عمومی + مخزن اختصاصی همان نوع قطعه.
     *
     * ادغام می‌شوند تا نظرهای یک محصول همه دور یک موضوع نچرخند؛ جمله‌های
     * تخصصی دو بار وارد می‌شوند تا شانس انتخابشان بیشتر باشد ولی انحصاری نه.
     *
     * @param  array<string,string[]>  $pool
     * @return string[]
     */
    public static function merged(array $pool, string $domain): array
    {
        $generic = $pool['generic'] ?? [];
        $special = $pool[$domain] ?? [];

        return array_merge($generic, $special, $special);
    }
