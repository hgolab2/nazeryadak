-- ---------------------------------------------------------------------------
-- گام ۰) بررسی: آیا ستون از قبل هست؟ (اگر خروجی داشت، ادامه ندهید)
-- ---------------------------------------------------------------------------
SHOW COLUMNS FROM `customers` LIKE 'phone_verified_at';


-- ---------------------------------------------------------------------------
-- گام ۱) خودِ ستون
--
-- NULL یعنی «شماره‌اش تأیید نشده». تاریخ یعنی همان لحظه‌ای که مشتری کد
-- پیامکی را درست وارد کرده است.
-- ---------------------------------------------------------------------------
ALTER TABLE `customers`
    ADD COLUMN `phone_verified_at` TIMESTAMP NULL DEFAULT NULL AFTER `phone`;


-- ---------------------------------------------------------------------------
-- گام ۲) مشتری‌های فعلی
--
-- تنها راهی که یک مشتری خودش حساب می‌سازد، همان مسیر کد پیامکی است؛ پس
-- هرکس یک بار وارد شده شماره‌اش را هم تأیید کرده. حساب‌هایی که ادمین از
-- پنل ساخته این ستون را ندارند و درست هم همین است که تأییدنشده بمانند —
-- آن‌ها همان‌هایی هستند که کد تأیید در پیامک سفارششان می‌آید.
--
-- بدون این گام، همه‌ی مشتری‌های قدیمی یک‌شبه «تأییدنشده» می‌شدند و در
-- اولین سفارش، کد اضافه در پیامک می‌گرفتند.
-- ---------------------------------------------------------------------------
UPDATE `customers`
SET `phone_verified_at` = `last_login_at`
WHERE `phone_verified_at` IS NULL
  AND `last_login_at` IS NOT NULL;


-- ---------------------------------------------------------------------------
-- گام ۳) ثبت در دفتر مهاجرت‌ها
--
-- لازم است وگرنه هر بار که بعدا «php artisan migrate» اجرا شود، دوباره
-- سراغ همین تغییر می‌رود و با «Duplicate column name» می‌شکند.
--
-- شماره‌ی batch از روی آخرین دسته حساب می‌شود. زیرکوئری داخل جدول موقت
-- پیچیده شده چون MySQL اجازه نمی‌دهد در INSERT از خودِ همان جدول بخوانید.
-- ---------------------------------------------------------------------------
INSERT INTO `migrations` (`migration`, `batch`)
SELECT '2026_09_10_000000_add_phone_verified_at_to_customers',
       COALESCE(MAX(`batch`), 0) + 1
FROM (SELECT `batch` FROM `migrations`) AS `current_batches`;


-- ---------------------------------------------------------------------------
-- گام ۴) بررسی نهایی
-- ---------------------------------------------------------------------------
SELECT COUNT(*)                                             AS `همه`,
       SUM(`phone_verified_at` IS NOT NULL)                 AS `تأییدشده`,
       SUM(`phone_verified_at` IS NULL)                     AS `تأییدنشده`
FROM `customers`;


