-- ---------------------------------------------------------------------------
-- ۱) مجموع بازدید، روی خودِ محصول
--
-- یک عدد کنار محصول، تا نمایش «چند نفر این قطعه را دیده‌اند» هیچ کوئری اضافه‌ای
-- نخواهد.
-- ---------------------------------------------------------------------------

ALTER TABLE `products`
    ADD COLUMN `views_count` BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER `rating_count`;


-- ---------------------------------------------------------------------------
-- ۲) بازدید روزانه: یک ردیف به‌ازای «محصول × روز»
--
-- ریل «پیشنهاد ویژه»ی صفحه‌ی اصلی باید پربازدیدهای دو روز اخیر را پیدا کند، پس
-- مجموعِ کل کافی نیست و بازدید باید تاریخ‌دار ذخیره شود. با یک ردیف برای هر
-- بازدید، جدول در چند هفته از کنترل خارج می‌شد؛ همان الگوی not_found_logs
-- به‌کار رفته است: ردیف روزانه، با شمارنده.
--
-- viewed_on از نوع DATE است نه TIMESTAMP، چون پنجره‌ی «دو روز اخیر» روی همین
-- ستون مقایسه می‌شود.
-- ---------------------------------------------------------------------------

CREATE TABLE `product_views` (
    `id`         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `product_id` BIGINT UNSIGNED NOT NULL,
    `viewed_on`  DATE NOT NULL,
    `hits`       BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    `updated_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),

    -- شمارنده با update-then-insert بالا می‌رود؛ این ایندکس یکتا تضمین می‌کند دو
    -- درخواست هم‌زمان دو ردیف برای یک روز نسازند.
    UNIQUE KEY `product_views_product_day_unique` (`product_id`, `viewed_on`),

    -- کوئری صفحه‌ی اصلی: جمع hits روی بازه‌ی تاریخ، مرتب‌شده نزولی.
    KEY `product_views_day_hits_index` (`viewed_on`, `hits`)
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- موتور جدول عمدا مشخص نشده تا همان پیش‌فرض سرور باشد؛ این‌طور نتیجه‌ی این فایل
-- و نتیجه‌ی «php artisan migrate» یکی می‌شود و با بقیه‌ی جدول‌های پروژه هم‌خوان
-- می‌ماند.


