-- ---------------------------------------------------------------------------
-- ۱) پیش‌فرض وضعیت نظر
--
-- نظر تازه دیگر پشت صف تأیید نمی‌ماند. پیش‌فرض ستون هم عوض می‌شود تا هر
-- مسیر درجی که وضعیت را صریح نمی‌دهد، نظر را منتشر کند.
-- ---------------------------------------------------------------------------

ALTER TABLE `product_reviews`
    MODIFY `status` VARCHAR(20) NOT NULL DEFAULT 'approved';


-- ---------------------------------------------------------------------------
-- ۲) نظرهای در انتظارِ باقی‌مانده
--
-- این‌ها نظرهای واقعی کاربران‌اند که فقط پشت صف تأیید مانده بودند. نظرهای
-- ردشده (rejected) دست‌نخورده می‌مانند؛ مدیر عمدا برشان داشته است.
-- ---------------------------------------------------------------------------

UPDATE `product_reviews` SET `status` = 'approved' WHERE `status` = 'pending';


-- ---------------------------------------------------------------------------
-- ۳) بازمحاسبه‌ی امتیاز محصولات
--
-- rating_count و rating_avg از روی نظرهای تأییدشده روی products ذخیره شده‌اند
-- و بعد از تأیید انبوه باید دوباره حساب شوند. updated_at محصول عمدا دست
-- نمی‌خورد؛ این ستون در lastmod نقشه‌ی سایت می‌آید و تأیید یک نظر نباید به
-- گوگل بگوید مشخصات قطعه عوض شده است.
-- ---------------------------------------------------------------------------

UPDATE `products` p
LEFT JOIN (
    SELECT `product_id`, COUNT(*) AS `cnt`, ROUND(AVG(`rating`), 2) AS `avg_rating`
    FROM `product_reviews`
    WHERE `status` = 'approved'
    GROUP BY `product_id`
) r ON r.`product_id` = p.`id`
SET p.`rating_count` = COALESCE(r.`cnt`, 0),
    p.`rating_avg`   = r.`avg_rating`;
