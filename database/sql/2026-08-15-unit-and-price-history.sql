-- ---------------------------------------------------------------------------
-- ۱) واحد شمارش و تعداد در بسته
--
-- ستون «واحد شمارش» از اول در فایل stkstock بود ولی ایمپورتر دورش می‌ریخت.
-- حالا ذخیره می‌شود و در صفحه‌ی محصول به کاربر نمایش داده می‌شود: کسی که
-- واحدش «دست ۴ عددي» است باید بداند با یک خرید چهار عدد تحویل می‌گیرد.
--
-- pack_qty فقط وقتی پر می‌شود که از روی متنِ واحد قابل استخراج باشد
-- («عدد»→۱ ، «جفت»→۲ ، «دست ۴ عددي»→۴). برای واحدهای حجمی و وزنی مثل
-- «گالن ۴ليتري» یا «كيلوگرم» مقدارش NULL می‌ماند چون «تعداد» معنا ندارد.
-- ---------------------------------------------------------------------------

ALTER TABLE `products`
    ADD COLUMN `unit`     VARCHAR(50) COLLATE utf8mb4_unicode_ci NULL DEFAULT NULL AFTER `stock`,
    ADD COLUMN `pack_qty` INT UNSIGNED NULL DEFAULT NULL AFTER `unit`;


-- ---------------------------------------------------------------------------
-- ۲) تاریخچه‌ی قیمت
--
-- جدولی فقط-افزودنی: هر بار قیمت یک محصول عوض شود یک ردیف اضافه می‌شود.
-- تا امروز ایمپورت، قیمت را در جا بازنویسی می‌کرد و هیچ ردی از قیمت قبلی
-- نمی‌ماند؛ حالا هم نمودار صفحه‌ی محصول از همین جدول ساخته می‌شود و هم
-- می‌شود فهمید یک قطعه کِی و چقدر گران شده است.
--
-- price تومانی است (همان عددی که در products.price ذخیره می‌شود).
-- source یعنی این تغییر از کجا آمده: import (فایل اکسل) یا admin (ویرایش دستی).
-- ---------------------------------------------------------------------------

CREATE TABLE `product_price_history` (
    `id`         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    `product_id` BIGINT UNSIGNED NOT NULL,
    `price`      BIGINT NOT NULL,
    `source`     VARCHAR(20) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'import',
    `created_at` TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (`id`),
    KEY `pph_product_created_index` (`product_id`, `created_at`)
) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- موتور جدول عمدا مشخص نشده تا همان پیش‌فرض سرور باشد؛ این‌طور نتیجه‌ی این
-- فایل و نتیجه‌ی «php artisan migrate» یکی می‌شود و با بقیه‌ی جدول‌های
-- پروژه (products، product_reviews، discount_codes و ...) هم‌خوان می‌ماند.


-- ---------------------------------------------------------------------------
-- ۳) نقطه‌ی شروع نمودار (اختیاری ولی توصیه‌شده)
--
-- قیمت فعلی همه‌ی محصولات به‌عنوان اولین نقطه‌ی تاریخچه ثبت می‌شود، وگرنه
-- نمودار تا اولین ایمپورتِ بعدی فقط یک نقطه دارد و چیزی برای نشان‌دادن نیست.
--
-- تاریخ را updated_at خودِ محصول می‌گذاریم چون قیمت فعلی از همان زمان است.
-- ---------------------------------------------------------------------------

INSERT INTO `product_price_history` (`product_id`, `price`, `source`, `created_at`)
SELECT `id`, `price`, 'seed', COALESCE(`updated_at`, NOW())
FROM `products`
WHERE `price` > 0;
