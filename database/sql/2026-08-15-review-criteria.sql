-- ---------------------------------------------------------------------------
-- امتیاز به تفکیک معیار
--
-- هر نظر تا امروز یک عدد ۱ تا ۵ داشت. «۳ ستاره» به خریدار بعدی نمی‌گوید
-- ایراد از کیفیت ساخت بوده یا از قیمت. حالا کنارِ امتیاز کلی، امتیاز هر
-- معیار (کیفیت ساخت، ارزش خرید، تناسب و نصب، دوام) هم ذخیره می‌شود.
--
-- ساختار مقدار، یک آبجکت ساده است:
--   {"quality": 5, "value": 4, "fitment": 5, "durability": 4}
--
-- کلیدها در App\Models\ProductReview::CRITERIA تعریف شده‌اند؛ اضافه‌کردن
-- معیار تازه فقط همان‌جا انجام می‌شود و به تغییر دیتابیس نیاز ندارد.
--
-- ستون NULL می‌پذیرد: نظرهای قبلی و نظرهایی که کاربر معیارها را رد می‌کند
-- بدون این ریزامتیازها ثبت می‌شوند و همچنان معتبرند.
-- ---------------------------------------------------------------------------

ALTER TABLE `product_reviews`
    ADD COLUMN `criteria` JSON NULL DEFAULT NULL AFTER `rating`;

