     * شناسه‌ی دسته‌های مجموعه‌بندی. هر شناسه‌ی دیگری در product_in_category
     * متعلق به دسته‌های مدل خودرو است که ایمپورت می‌سازد.
     *
     * @return array<int,int>
     */
    public static function groupingIds(): array
    {
        return array_column(ProductCategory::cases(), 'value');
    }

    /** شناسه‌ی مجموعه‌ی قطعه؛ اگر هیچ کلیدواژه‌ای نخورد، «سایر قطعات». */
    public function detect(string $title): int
    {
        $title = mb_strtolower(strtr($title, [
            'ي' => 'ی',
            'ك' => 'ک',
            '‌' => ' ',
        ]));

        foreach ($this->rules as $categoryId => $keywords) {
            foreach ($keywords as $keyword) {
                if (mb_strpos($title, mb_strtolower($keyword)) !== false) {
                    return $categoryId;
                }
            }
        }

        return self::OTHER;
    }
