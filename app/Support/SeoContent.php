    /**
     * کد موتور از دل شرح کاملِ آن: «موتور TU3 با حجم ۱۴۰۰...» ← «موتور TU3 و TU5».
     *
     * شرح کامل برای متن صفحه لازم است ولی در توضیحات متا (۱۵۸ کاراکتر) جا
     * نمی‌شود. کد موتور تنها چیزی است که خودروها را از هم جدا می‌کند، پس
     * همان استخراج می‌شود؛ اگر خودرویی کد موتور استاندارد نداشت، حجم موتور
     * جایگزین می‌شود و اگر آن هم نبود، این بخش از جمله حذف می‌شود.
     */
    private static function engineShort(string $engine): string
    {
        if (preg_match_all('/\b(?:TU\d[A-Z]?|XU\d|EF\d[A-Z]*|K\d+M|OHV)\b/u', $engine, $matches)) {
            $codes = array_values(array_unique($matches[0]));

            return 'موتور ' . implode(' و ', $codes);
        }

        if (preg_match('/([۰-۹0-9]{3,4})\s*سی‌سی/u', $engine, $match)) {
            return 'موتور ' . static::fa($match[1]) . ' سی‌سی';
        }

        return 'قطعات اصلی';
    }

    /** ارقام لاتینِ داخل نام‌ها («پژو 206») به فارسی؛ متن سئو باید فارسی خوانده شود. */
    private static function fa(string $text): string
    {
        return (string) toPersianNumbers($text, false);
    }

    /**
     * عدد گرد شده: «بیش از ۶۰۰ قطعه».
     *
     * تعداد دقیق با هر ورود و خروج کالا عوض می‌شود و متنِ ذخیره‌شده را کهنه
     * می‌کند؛ عدد گرد، هم درست می‌ماند و هم لازم نیست هر روز بازتولید شود.
     */
    private static function approx(int $count): string
    {
        if ($count < 10) {
            return static::fa((string) $count);
        }

        $step    = $count >= 100 ? 50 : 10;
        $rounded = intdiv($count, $step) * $step;

        return 'بیش از ' . static::fa((string) $rounded);
    }

    /** @param string[] $items */
    private static function join(array $items): string
    {
        $items = array_values(array_filter($items));

        if (count($items) <= 1) {
            return (string) ($items[0] ?? '');
        }

        $last = array_pop($items);

        return implode('، ', $items) . ' و ' . $last;
    }

    /** @param string[] $blocks */
    private static function html(array $blocks): string
    {
        return implode("\n", array_filter($blocks));
    }

    private static function p(string $text): string
    {
        return '<p>' . $text . '</p>';
    }

    private static function h2(string $text): string
    {
        return '<h2>' . $text . '</h2>';
    }

    private static function h3(string $text): string
    {
        return '<h3>' . $text . '</h3>';
    }

    /** @param string[] $items */
    private static function ul(array $items): string
    {
        return $items ? '<ul><li>' . implode('</li><li>', $items) . '</li></ul>' : '';
    }

    /** @param string[] $items */
    private static function ol(array $items): string
    {
        return $items ? '<ol><li>' . implode('</li><li>', $items) . '</li></ol>' : '';
    }
