    /** آیا برای این خودرو، دانش اختصاصی ثبت شده است؟ */
    public static function hasCar(string $carSlug): bool
    {
        return isset(static::carFacts()[$carSlug]);
    }

    /**
     * محتوای صفحه‌ی دسته‌بندی: /shop/{slug}
     *
     * @return array<string, mixed>|null
     */
    public static function forCategory(string $categorySlug): ?array
    {
        $facts = static::categoryFacts()[$categorySlug] ?? null;
        $case  = ProductCategory::fromSlug($categorySlug);

        if ($facts === null || $case === null) {
            return null;
        }

        $label = $case->label();

        $intro = static::html([
            static::p($facts['lead']),
            static::h2('چه قطعاتی در گروه ' . $label . ' قرار می‌گیرند؟'),
            static::ul($facts['parts']),
        ]);

        $body = static::html([
            static::h2('نشانه‌های خرابی در ' . $label),
            static::p('اگر یکی از این نشانه‌ها را در خودروی خود می‌بینید، بررسی این گروه از قطعات را در اولویت بگذارید:'),
            static::ul($facts['symptoms']),
            static::h2('بازه‌ی تعویض'),
            static::p($facts['interval']),
            static::h2('راهنمای خرید ' . $label),
            static::ul($facts['tips']),
            static::h3('خرید از ناظر یدک'),
            static::p('همه‌ی قطعات این گروه در ناظر یدک با ضمانت اصالت عرضه می‌شوند و امکان بررسی کد فنی پیش از خرید وجود دارد. اگر قطعه‌ی موردنظرتان را پیدا نکردید یا در انتخاب کد فنی تردید دارید، کارشناسان ما از طریق <a href="/contact-us">صفحه‌ی تماس با ما</a> پاسخگو هستند.'),
        ]);

        return [
            'name'            => $label,
            'heading'         => 'خرید ' . $label,
            'intro'           => $intro,
            'body'            => $body,
            'faq'             => $facts['faq'],
            'seo_title'       => 'خرید ' . $label . ' | قیمت و کد فنی قطعات اصلی',
            'seo_description' => seo_description('خرید ' . $label . ' با ضمانت اصالت کالا؛ راهنمای انتخاب، نشانه‌های خرابی، بازه‌ی تعویض و قیمت روز قطعات اصلی در فروشگاه ناظر یدک.'),
            'focus_keyword'   => $facts['keyword'],
            'robots_index'    => true,
        ];
    }

